// Every skill tag the factory knows a fast LOCAL generator for (no model call).
// Anything not in here is generated by the model with a skill-specific prompt.
export const LOCALLY_GENERATED_SKILLS = new Set([
  "addition-within-5",
  "addition-within-20",
  "subtraction-within-20",
  "addition-within-100",
  "subtraction-within-100",
  "shape-names",
  "shape-sides",
]);

export function skillsFor(grade, subject) {
  return (CURRICULUM[grade] && CURRICULUM[grade][subject]) || [];
}

// Build a balanced list of generation targets, at most `count` of them, spread
// across grades and subjects so no single grade/subject dominates a weekly run.
// Each target: { grade, subject, quizType, skill }.
export function generationTargets(count = 50, opts = {}) {
  const grades = opts.grades || GRADES;
  const subjects = opts.subjects || SUBJECTS;
  // Flatten every (grade, subject, skill) combination the map defines.
  const all = [];
  for (const grade of grades) {
    for (const subject of subjects) {
      for (const skill of skillsFor(grade, subject)) {
        all.push({ grade, subject, quizType: SUBJECT_TO_QUIZTYPE[subject] || subject, skill });
      }
    }
  }
  if (!all.length) return [];
  // Round-robin by (grade+subject) bucket so the mix stays even as we fill up to
  // `count`. We cycle skills within each bucket too.
  const buckets = new Map();
  for (const t of all) {
    const k = `${t.grade}|${t.subject}`;
    if (!buckets.has(k)) buckets.set(k, []);
    buckets.get(k).push(t);
  }
  const order = [...buckets.keys()];
  const out = [];
  let i = 0;
  const cursor = new Map(order.map((k) => [k, 0]));
  let safety = count * 4 + order.length;
  while (out.length < count && safety-- > 0) {
    const k = order[i % order.length];
    const list = buckets.get(k);
    const c = cursor.get(k);
    if (c < list.length) {
      out.push(list[c]);
      cursor.set(k, c + 1);
    } else if (list.length) {
      // Bucket exhausted its distinct skills; reuse from the top so a weekly run
      // can still reach the target volume (the factory de-dupes by content).
      out.push(list[c % list.length]);
      cursor.set(k, c + 1);
    }
    i++;
  }
  return out.slice(0, count);
}

export default { GRADES, SUBJECTS, CURRICULUM, SUBJECT_TO_QUIZTYPE, LOCALLY_GENERATED_SKILLS, skillsFor, generationTargets };
