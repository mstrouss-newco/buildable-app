// /api/_curriculum.js
// -------------------------------------------------------------
// The curriculum map for Buildable's Learning Mode (Session 8A).
// One place that says WHAT to practice at each grade and subject, so the weekly
// question factory (api/generate-question-bank.js) makes a balanced, standards-
// shaped mix, and generate-quiz can tag questions with a real skill.
//
// Shape: CURRICULUM[grade][subject] = [skill, skill, ...]
//   grade:   'k','1','2','3','4','5','6'
//   subject: 'math' | 'geometry' | 'spelling' | 'reading'
//   skill:   a short, stable tag (kebab-case). These tags match the ones the
//            quiz payloads carry, so the parent dashboard can report by skill.
//
// Keep it plain data. No emojis anywhere (product rule).
// -------------------------------------------------------------

export const GRADES = ["k", "1", "2", "3", "4", "5", "6"];
export const SUBJECTS = ["math", "geometry", "spelling", "reading"];

// quizType mirrors subject one-to-one today, but keep the mapping explicit so a
// subject could point at a different generator later without touching callers.
export const SUBJECT_TO_QUIZTYPE = {
  math: "math",
  geometry: "geometry",
  spelling: "spelling",
  reading: "reading",
};

